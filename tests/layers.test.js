import assert from 'node:assert/strict';
import { test } from 'node:test';
import { compileStylesheet, DEFAULT_LAYERS, resolveLayers } from '../src/compile/stylesheet.js';
import { css } from '../src/index.js';

const style = { a: { color: 'var(--x)' } };
const calls = [
  { kind: 'globals', value: { body: { margin: 0 } } },
  { kind: 'create', value: style },
];

test('the default layers are three sublayers of purser', () => {
  const { css: out } = compileStylesheet({ calls });
  assert.ok(out.startsWith('/* Generated by purser. Do not edit. */\n@layer purser.tokens, purser.globals, purser.atoms;\n'));
  assert.match(out, /\n@layer purser\.globals \{\n/);
  assert.match(out, /\n@layer purser\.atoms \{\n/);
});

test('named layers rename the statement and every block', () => {
  const layers = { tokens: 'purser-tokens', globals: 'purser-globals', atoms: 'purser-atoms' };
  const { css: out, diagnostics } = compileStylesheet({ calls, layers });
  assert.deepEqual(diagnostics, []);
  assert.ok(out.includes('\n@layer purser-tokens, purser-globals, purser-atoms;\n'));
  assert.match(out, /\n@layer purser-globals \{\n {2}body \{\n {4}margin-bottom: 0;\n {4}margin-left: 0;\n {4}margin-right: 0;\n {4}margin-top: 0;\n {2}\}/);
  assert.match(out, new RegExp(`\\n@layer purser-atoms \\{\\n {2}\\.${css.create(style).a.color} \\{ color: var\\(--x\\); \\}`));
  assert.ok(!/@layer purser\./.test(out));
});

test('a partial layers option keeps the defaults for the others', () => {
  assert.deepEqual(resolveLayers({ globals: 'base.purser' }), { ...DEFAULT_LAYERS, globals: 'base.purser' });
  assert.deepEqual(resolveLayers(), DEFAULT_LAYERS);
});

test('layer names are validated', () => {
  assert.throws(() => resolveLayers({ atoms: 'two words' }), /is not a CSS layer name/);
  assert.throws(() => resolveLayers({ atoms: '1st' }), /is not a CSS layer name/);
  assert.throws(() => resolveLayers({ atoms: 'a..b' }), /is not a CSS layer name/);
  assert.throws(() => resolveLayers({ atoms: 'purser.globals' }), /three different names/);
  assert.throws(() => resolveLayers({ utilities: 'u' }), /unknown layer "utilities"/);
});
