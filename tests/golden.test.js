import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { test } from 'node:test';
import { build } from '../src/build/index.js';
import { ROOT, tryRequire } from './helpers/host.js';

const skip = tryRequire('typescript') ? false : 'typescript is not installed in the host project';
const app = path.join(ROOT, 'tests/fixtures/app');
const golden = path.join(app, 'expected.css');
const options = { projectDir: app, src: ['app', 'components', 'lib'], tokens: 'lib/tokens.ts' };

test('the fixture app compiles to the golden stylesheet', { skip }, async () => {
  const result = await build(options);
  assert.deepEqual(result.diagnostics, []);
  if (process.env.UPDATE_GOLDEN) fs.writeFileSync(golden, result.css);
  assert.equal(result.css, fs.readFileSync(golden, 'utf8'));
});

test('output is deterministic across builds', { skip }, async () => {
  const a = await build(options);
  const b = await build(options);
  assert.equal(a.css, b.css);
});

test('the output obeys the rules it promises', { skip }, async () => {
  const { css } = await build(options);
  assert.ok(!/!\s*important/i.test(css));
  assert.ok(css.startsWith('/* Generated by purser. Do not edit. */\n@layer purser.tokens, purser.globals, purser.atoms;\n'));
  // Every colour literal is lab().
  assert.ok(!/#[0-9a-f]{3,8}\b|\b(rgba?|hsla?|hwb|oklch|oklab|lch)\(/i.test(css));
  // Each (context, selector, property) appears once.
  const postcss = tryRequire('postcss');
  if (postcss) {
    const { selfCheck } = await import('../src/build/selfcheck.js');
    assert.deepEqual(selfCheck(css, postcss), []);
  }
});

test('runtime class names equal build class names (the page fixture)', { skip }, async () => {
  const page = path.join(ROOT, 'tests/fixtures/page');
  const result = await build({ projectDir: page, src: ['.'], tokens: 'tokens.js' });
  assert.deepEqual(result.diagnostics, []);
  const { renderBody } = await import(path.join(page, 'page.js'));
  const classes = new Set(renderBody().match(/class="([^"]*)"/g).flatMap((m) => m.slice(7, -1).split(' ')));
  assert.ok(classes.size > 20);
  for (const cls of classes) assert.ok(result.css.includes(`.${cls}`), `class ${cls} has CSS`);
});
